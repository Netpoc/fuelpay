"""Historical data generation.

Replays the pure simulation stepper from a point in the past up to `until`,
writing the readings and events it produces. This is the same `step_site()` the
live ticker calls — history and live data are generated by one code path, so
they cannot drift apart in shape or statistics.

Backfill runs per *site*, not per generator: bulk storage is shared, so its
level can only be advanced with every generator drawing on it in view. The
final state is persisted to `simulation_state` and `tank_simulation_state`,
which is where the live ticker picks up.
"""

import logging
import uuid
from datetime import UTC, datetime, timedelta

from sqlalchemy import or_, select
from sqlalchemy.ext.asyncio import AsyncSession

from app.models.entities import (
    Generator,
    GeneratorStatus,
    Organisation,
    SimulationState,
    SimulationStatus,
    Site,
    Tank,
    TankKind,
    Vehicle,
)
from app.services.persistence import (
    insert_events,
    insert_readings,
    insert_tank_readings,
    save_site_state,
    touch_tank_last_seen,
)
from app.simulation.engine import GeneratorSpec, SiteSpec, TankSpec, initial_site_state
from app.simulation.field import FieldGeometry
from app.simulation.site import run_site_span
from app.simulation.vehicle import VehicleSpec

logger = logging.getLogger(__name__)


def _tank_spec(tank: Tank) -> TankSpec:
    return TankSpec(
        id=tank.id,
        organisation_id=tank.organisation_id,
        kind=tank.kind,
        capacity_l=tank.capacity_l,
        reorder_threshold_pct=tank.reorder_threshold_pct,
    )


def _tenant_active():
    """Organisations the simulator should still advance: every real tenant,
    and demo tenants until they expire."""
    return or_(
        Organisation.is_demo.is_(False),
        Organisation.demo_expires_at > datetime.now(UTC),
    )


async def load_site_specs(
    session: AsyncSession,
    organisation_id: uuid.UUID | None = None,
    generator_id: uuid.UUID | None = None,
    site_id: uuid.UUID | None = None,
    only_live: bool = True,
) -> list[SiteSpec]:
    """Build simulation specs for every active generator, grouped by site.

    Both filters are optional and compose. Passing them together is how the
    simulate endpoints scope a single unit to the calling tenant in one query,
    so a foreign generator id simply yields no rows rather than leaking that it
    exists.

    A generator with no day tank is skipped: an uninstrumented tank is invisible
    to FuelPay, so there is nothing to simulate a level for. A site whose bulk
    tanks are all uninstrumented still runs — its generators burn what is in
    their day tanks — it simply has no visible upstream.

    `only_live` (the default, and what the ticker uses) skips sites whose
    history is still being generated and tenants whose demo has expired.
    Advancing a PENDING site would give it a cursor at "now", and its backfill
    would then skip it as already simulated. The demo backfill job passes
    False with a `site_id` to load the one site it is working on.
    """
    query = (
        select(Generator, Site, Tank)
        .join(Site, Site.id == Generator.site_id)
        .join(Tank, (Tank.generator_id == Generator.id) & (Tank.kind == TankKind.DAY))
        .join(Organisation, Organisation.id == Generator.organisation_id)
        .where(Generator.status == GeneratorStatus.ACTIVE)
        .order_by(Generator.serial)
    )
    if only_live:
        query = query.where(Site.simulation_status == SimulationStatus.LIVE, _tenant_active())
    if site_id is not None:
        query = query.where(Site.id == site_id)
    if organisation_id is not None:
        query = query.where(Generator.organisation_id == organisation_id)
    if generator_id is not None:
        query = query.where(Generator.id == generator_id)

    rows = (await session.execute(query)).all()
    if not rows:
        return []

    site_ids = {site.id for _, site, _ in rows}
    bulk_rows = (
        (
            await session.execute(
                select(Tank)
                .where(Tank.site_id.in_(site_ids), Tank.kind == TankKind.BULK)
                .order_by(Tank.name)
            )
        )
        .scalars()
        .all()
    )
    bulk_by_site: dict[uuid.UUID, list[Tank]] = {}
    for tank in bulk_rows:
        bulk_by_site.setdefault(tank.site_id, []).append(tank)

    generators_by_site: dict[uuid.UUID, list[GeneratorSpec]] = {}
    sites_by_id: dict[uuid.UUID, Site] = {}
    for generator, site, day_tank in rows:
        sites_by_id[site.id] = site
        generators_by_site.setdefault(site.id, []).append(
            GeneratorSpec(
                id=generator.id,
                organisation_id=generator.organisation_id,
                kva_rating=generator.kva_rating,
                power_factor=generator.power_factor,
                profile=site.profile,
                latitude=site.latitude,
                longitude=site.longitude,
                day_tank=_tank_spec(day_tank),
            )
        )

    return [
        SiteSpec(
            id=site_id,
            organisation_id=sites_by_id[site_id].organisation_id,
            profile=sites_by_id[site_id].profile,
            bulk_tanks=tuple(_tank_spec(t) for t in bulk_by_site.get(site_id, [])),
            generators=tuple(specs),
        )
        for site_id, specs in generators_by_site.items()
    ]


def vehicle_spec(vehicle: Vehicle) -> VehicleSpec:
    return VehicleSpec(
        id=vehicle.id,
        organisation_id=vehicle.organisation_id,
        engine_kw=vehicle.engine_kw,
        tank_capacity_l=vehicle.tank_capacity_l,
        yard_latitude=vehicle.yard_latitude,
        yard_longitude=vehicle.yard_longitude,
        field=FieldGeometry(
            latitude=vehicle.field_latitude,
            longitude=vehicle.field_longitude,
            width_m=vehicle.field_width_m,
            length_m=vehicle.field_length_m,
            heading_deg=vehicle.field_heading_deg,
        ),
        primary_operation=vehicle.primary_operation,
        working_hours_start=vehicle.working_hours_start,
        working_hours_end=vehicle.working_hours_end,
        utc_offset_hours=vehicle.utc_offset_hours,
    )


async def load_vehicle_specs(
    session: AsyncSession,
    vehicle_id: uuid.UUID | None = None,
    only_live: bool = True,
) -> list[VehicleSpec]:
    """Specs for machines to simulate. Same `only_live` rule as sites."""
    query = select(Vehicle).join(Organisation, Organisation.id == Vehicle.organisation_id)
    if only_live:
        query = query.where(Vehicle.simulation_status == SimulationStatus.LIVE, _tenant_active())
    if vehicle_id is not None:
        query = query.where(Vehicle.id == vehicle_id)
    rows = (await session.execute(query.order_by(Vehicle.serial))).scalars().all()
    return [vehicle_spec(vehicle) for vehicle in rows]


async def backfill_site_specs(
    session: AsyncSession,
    specs: list[SiteSpec],
    days: int,
    until: datetime,
    minutes_per_step: int,
    seed: int,
) -> tuple[int, int]:
    """Generate `days` of history ending at `until`. Returns (readings, events).

    Sites whose generators already hold simulation state are skipped: their
    history has been generated once already, and regenerating it would
    duplicate events (which have no natural key to conflict on) even though
    readings would not.
    """
    if not specs:
        return 0, 0

    existing = set((await session.execute(select(SimulationState.generator_id))).scalars().all())
    pending = [
        spec for spec in specs if not any(g.id in existing for g in spec.generators)
    ]
    if not pending:
        logger.info("backfill skipped: all %d sites already have state", len(specs))
        return 0, 0

    start = until - timedelta(days=days)
    total_readings = 0
    total_events = 0

    for spec in pending:
        state = initial_site_state(spec, start, seed)
        state, readings, tank_readings, events = run_site_span(
            spec, state, until, minutes_per_step, seed
        )

        total_readings += await insert_readings(session, readings)
        await insert_tank_readings(session, tank_readings)
        await touch_tank_last_seen(session, tank_readings)
        total_events += await insert_events(session, events)
        await save_site_state(session, spec, state)

    logger.info(
        "backfilled %d sites over %d days: %d readings, %d events",
        len(pending),
        days,
        total_readings,
        total_events,
    )
    return total_readings, total_events
